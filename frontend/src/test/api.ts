/** A handler may return a promise, so a test can hold a response open and observe the loading state. */
type Handler = (url: URL) => unknown;

export const problem = (status: number, title: string, detail: string): Response =>
  new Response(JSON.stringify({ type: "about:blank", title, status, detail } satisfies Problem), {
    status,
    headers: { "Content-Type": "application/problem+json" },
  });

const DEFAULT_ROUTES: [RegExp, Handler][] = [
  [/\/meta$/, () => meta],
  [/\/predictions\/upcoming$/, () => upcoming],
  [/\/predictions\/matchup$/, (u) => matchup(u.searchParams.get("home")!, u.searchParams.get("away")!)],
  [/\/predictions\/live$/, () => live],
  [/\/predictions\/log$/, (u) => predictionLog(u)],
  [
    /\/seasons\/(\d+)\/simulation$/,
    (u) => simulation(Number(u.pathname.split("/")[4]), Number(u.searchParams.get("as_of_matchweek")) || null),
  ],
  [/\/seasons\/\d+\/fixtures$/, () => finished],
  [/\/evaluation\/backtest$/, () => backtest],
  [/\/models$/, () => models],
  [/\/ratings$/, () => ratings],
  [/\/teams$/, () => teams],
  [/\/teams\/\d+\/elo$/, () => elo],
];

/** Stub `fetch`; `overrides` take precedence over the default routes. Returns the recorded request URLs. */
export function mockApi(overrides: [RegExp, Handler][] = []): URL[] {
  const calls: URL[] = [];
  const routes = [...overrides, ...DEFAULT_ROUTES];
  vi.stubGlobal(
    "fetch",
    vi.fn(async (input: RequestInfo | URL) => {
      const url = new URL(String(input), "http://localhost");
      calls.push(url);
      const route = routes.find(([pattern]) => pattern.test(url.pathname));
      if (!route) return problem(404, "Not found", url.pathname);
      const body = await route[1](url);
      return body instanceof Response ? body : new Response(JSON.stringify(body), { status: 200 });
    }),
  );
  return calls;
}
