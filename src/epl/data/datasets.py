"""The datasets the platform can run on, and what each may be used for.

Every path the pipeline writes (raw snapshots, database, models, reports) is
scoped by dataset, so restricted data can never be mixed into a shareable
build. `redistributable` is the property that matters for publishing: only
datasets marked True may enter Git, the Docker image or published artifacts.
"""

from dataclasses import asdict, dataclass
from typing import Literal

DatasetName = Literal["demo", "openfootball", "premier-league"]


@dataclass(frozen=True)
class DatasetInfo:
    name: DatasetName
    label: str
    synthetic: bool
    redistributable: bool | None  # None = permission not established
    has_match_stats: bool
    license: str
    source_url: str | None
    notes: str

    def to_dict(self) -> dict[str, object]:
        return asdict(self)


DATASETS: dict[DatasetName, DatasetInfo] = {
    "demo": DatasetInfo(
        name="demo",
        label="Demo league (synthetic)",
        synthetic=True,
        redistributable=True,
        has_match_stats=True,
        license="Generated by this project (MIT). Fictional clubs; no real match data.",
        source_url=None,
        notes=(
            "Four seasons of a fictional 20-club league with promotion and relegation, simulated from "
            "drifting team strengths (`epl extract` with EPL_DATASET=demo regenerates it from a fixed seed). "
            "Results on it measure the pipeline, not real-world forecasting skill."
        ),
    ),
    "openfootball": DatasetInfo(
        name="openfootball",
        label="Premier League results (openfootball)",
        synthetic=False,
        redistributable=True,
        has_match_stats=False,
        license=(
            "Public-domain dedication by openfootball/football.json: "
            '"Use as you please with no restrictions whatsoever."'
        ),
        source_url="https://github.com/openfootball/football.json",
        notes=(
            "Fixtures and final scores only (no shots or possession), so stats-based features are "
            "unavailable. Community-maintained: the publisher gives no accuracy guarantee."
        ),
    ),
    "premier-league": DatasetInfo(
        name="premier-league",
        label="Premier League (official site API)",
        synthetic=False,
        redistributable=False,
        has_match_stats=True,
        license=(
            "Premier League website terms of use: material may not be reproduced, re-utilised or "
            "redistributed, and creating a database from downloaded material is prohibited."
        ),
        source_url="https://www.premierleague.com/terms-and-conditions",
        notes=(
            "Local, personal use only; permission for any use beyond the terms is not established. "
            "Raw snapshots, the database, trained models and reports built from it are excluded from Git "
            "and the Docker build context."
        ),
    ),
}


def dataset_info(name: DatasetName) -> DatasetInfo:
    return DATASETS[name]
